"""Maintain the team's submission + testing history and regenerate SUBMISSIONS.md from it.

The source of truth is submissions/<team>/submission_log.csv (one row per model that was
validated on the fixed split, whether or not it went to Kaggle). SUBMISSIONS.md is generated.

  # a file uploaded to Kaggle (after you get the public score)
  python common/update_submission_log.py --track classical --model tfidf_lr \
      --file classical/kaggle_submissions/2026-11-02_tfidf_lr.csv --public 0.9123 --author "Name"

  # a model tested on the fixed split but not submitted
  python common/update_submission_log.py --track classical --model nbsvm --val 0.9512 --author "Name"

  # private scores once revealed;  just rebuild the markdown
  python common/update_submission_log.py --model tfidf_lr --private 0.9001
  python common/update_submission_log.py --render

A row is keyed by (track, model, file): calling again with the same key updates the given
fields and leaves the others alone. --commit defaults to the last commit that touched --file
(or HEAD when there is no file). Paths are relative to the team folder.
"""
from __future__ import annotations

import argparse
import datetime as dt
import subprocess
from pathlib import Path

import pandas as pd

TEAM_DIR = Path(__file__).resolve().parent.parent
LOG = TEAM_DIR / "submission_log.csv"
MD = TEAM_DIR / "SUBMISSIONS.md"
REPO_URL = "https://github.com/ZhenmanShen/human-or-ai-submissions"
COLUMNS = ["date", "track", "model", "file", "commit", "author", "val_auroc",
           "kaggle_public", "kaggle_private", "notes"]
NOT_SUBMITTED = "not submitted"


def git(*args) -> str:
    return subprocess.run(["git", *args], cwd=TEAM_DIR, capture_output=True, text=True).stdout.strip()


def content_commit(path: str) -> str | None:
    """Oldest commit whose copy of `path` (followed across renames) equals the committed version: survives
    renames, and moves forward when a refit replaces the file under the same name."""
    head = git("rev-parse", f"HEAD:./{path}")
    if not head:
        return None
    hist = git("log", "--follow", "--format=%H", "--name-only", "--", path).split()
    pairs = list(zip(hist[::2], hist[1::2]))  # newest first: (commit, path in that commit)
    found = None
    for commit, p in pairs:
        if git("rev-parse", f"{commit}:{p}") != head:
            break
        found = commit
    return found


def read_log() -> pd.DataFrame:
    if LOG.exists():
        return pd.read_csv(LOG, dtype=str, keep_default_na=False)[COLUMNS]
    return pd.DataFrame(columns=COLUMNS)


def fmt(x) -> str:
    try:
        return f"{float(x):.5f}"
    except (TypeError, ValueError):
        return str(x)


def render(df: pd.DataFrame) -> str:
    lines = [
        "# Submission and testing history",
        "",
        "Generated by `common/update_submission_log.py` from `submission_log.csv` - do not edit by hand.",
        "Every model validated on the fixed 2,000-row split (`common/val_ids.csv`) has a row; models that were not",
        f"uploaded to Kaggle say \"{NOT_SUBMITTED}\". Kaggle private scores are blank until the competition ends.",
        "",
        "| date | track | model | submission file | commit | author | val AUROC (fixed split) | Kaggle public | Kaggle private | notes |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for _, r in df.iterrows():
        commit = f"[`{r.commit[:7]}`]({REPO_URL}/commit/{r.commit})" if r.commit else ""
        file = f"`{r.file}`" if r.file else ""
        lines.append(f"| {r.date} | {r.track} | {r.model} | {file} | {commit} | {r.author} | {fmt(r.val_auroc)} | "
                     f"{fmt(r.kaggle_public)} | {fmt(r.kaggle_private)} | {r.notes} |")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--track", default=None, help="pretrained | classical")
    ap.add_argument("--model", default=None)
    ap.add_argument("--file", default=None, help="submission CSV, relative to the team folder")
    ap.add_argument("--public", default=None)
    ap.add_argument("--private", default=None)
    ap.add_argument("--val", default=None, help="fixed-split validation AUROC")
    ap.add_argument("--author", default=None)
    ap.add_argument("--date", default=None, help="YYYY-MM-DD (default: today for new rows)")
    ap.add_argument("--commit", default=None)
    ap.add_argument("--notes", default=None)
    ap.add_argument("--render", action="store_true", help="only regenerate SUBMISSIONS.md")
    args = ap.parse_args()

    df = read_log()
    if not args.render:
        if not args.model:
            ap.error("--model is required")
        key = (df.model == args.model)
        if args.track:
            key &= df.track == args.track
        if args.file is not None:
            # a model's first submission fills in its "tested, not submitted" row; later files get new rows
            key = key & (df.file == args.file) if (key & (df.file == args.file)).any() else key & (df.file == "")
        if key.sum() > 1:
            ap.error(f"{key.sum()} rows match; add --track/--file to pick one")
        if key.sum() == 0:
            if not args.track:
                ap.error("new row: --track is required")
            df.loc[len(df)] = {c: "" for c in COLUMNS} | {
                "date": args.date or dt.date.today().isoformat(), "track": args.track, "model": args.model,
                "file": args.file or "", "kaggle_public": "pending upload" if args.file else NOT_SUBMITTED}
            key = df.index == len(df) - 1
        i = df.index[key][0]
        if args.file and not df.at[i, "file"]:  # submission file written, score not in yet
            df.at[i, "file"], df.at[i, "commit"] = args.file, ""
            if df.at[i, "kaggle_public"] == NOT_SUBMITTED:
                df.at[i, "kaggle_public"] = "pending upload"
            if not args.date:
                df.at[i, "date"] = dt.date.today().isoformat()
        if not args.commit:
            if df.at[i, "file"]:  # the commit that added the file's current content (blank until committed)
                args.commit = content_commit(df.at[i, "file"])
            elif args.val is not None or not df.at[i, "commit"]:  # code version that produced the val score
                args.commit = git("rev-parse", "HEAD")
        for col, val in [("date", args.date), ("author", args.author), ("val_auroc", args.val),
                         ("kaggle_public", args.public), ("kaggle_private", args.private),
                         ("commit", args.commit), ("notes", args.notes)]:
            if val is not None:
                df.at[i, col] = str(val)
        df.to_csv(LOG, index=False, lineterminator="\n")  # append order (union-merge friendly)
    MD.write_text(render(df.sort_values(["date", "track", "model"], kind="stable")), encoding="utf-8", newline="\n")
    print(f"{LOG.name}: {len(df)} rows -> {MD.name}")


if __name__ == "__main__":
    main()
