"""Q2: effect of labeled training-set size on a fixed validation set.

Run from the repository root:

    python -m src.q2_learning_curve --model masked_lr

The experiment uses nested, class-balanced subsets of the shared 8,000-row
training partition. Every point is evaluated on the same committed 2,000-row
validation set. Outputs are written under results/q2/<model>/ and a report
snippet is written to report/q2_learning_curve.tex.
"""
import argparse
import time
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd
from matplotlib.ticker import NullLocator
from sklearn.metrics import roc_auc_score

from .data import RESULTS_DIR, SPLIT_SEED, load_split
from .models import MODELS

TRAIN_SIZES = [500, 1_000, 2_000, 5_000, 8_000]


def nested_balanced_order(train: pd.DataFrame, seed: int) -> pd.DataFrame:
    """Return a deterministic class-balanced order whose prefixes are nested."""
    by_class = {
        label: train[train["label"] == label].sample(frac=1, random_state=seed).reset_index(drop=True)
        for label in (0, 1)
    }
    rows = []
    for i in range(max(len(by_class[0]), len(by_class[1]))):
        for label in (0, 1):
            if i < len(by_class[label]):
                rows.append(by_class[label].iloc[i])
    ordered = pd.DataFrame(rows).reset_index(drop=True)
    assert len(ordered) == len(train)
    return ordered


def make_plot(results: pd.DataFrame, path: Path) -> None:
    fig, ax = plt.subplots(figsize=(7.2, 4.5))
    ax.plot(results["training rows"], results["train AUROC"], marker="o", linewidth=2,
            label="Training AUROC")
    ax.plot(results["training rows"], results["validation AUROC"], marker="o", linewidth=2,
            label="Validation AUROC")
    ax.set_xscale("log")
    ax.set_xticks(TRAIN_SIZES, [f"{n:,}" for n in TRAIN_SIZES])
    ax.xaxis.set_minor_locator(NullLocator())
    floor = max(0.5, min(results["validation AUROC"].min(), results["train AUROC"].min()) - 0.02)
    ax.set_ylim(floor, 1.005)
    ax.set_xlabel("Number of labeled training examples")
    ax.set_ylabel("AUROC")
    ax.set_title("Learning curve on the fixed 2,000-row validation set")
    ax.grid(alpha=0.25)
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(path, dpi=220, bbox_inches="tight")
    plt.close(fig)


def interpretation(results: pd.DataFrame) -> str:
    first = results.iloc[0]
    last = results.iloc[-1]
    gaps = results["train AUROC"] - results["validation AUROC"]
    val_gains = results["validation AUROC"].diff()
    largest_idx = val_gains.idxmax()
    largest_from = int(results.loc[largest_idx - 1, "training rows"])
    largest_to = int(results.loc[largest_idx, "training rows"])
    final_gain = float(val_gains.iloc[-1])
    if final_gain < 0.002:
        ending = "The final increment is small, indicating diminishing returns from additional labels under this representation."
    else:
        ending = "The final increment remains measurable, so more labeled examples could still improve generalization."
    return (
        f"Using one fixed masked n-gram logistic-regression configuration, training AUROC is "
        f"{first['train AUROC']:.4f} with 500 examples and {last['train AUROC']:.4f} with 8,000, "
        f"while validation AUROC changes from {first['validation AUROC']:.4f} to "
        f"{last['validation AUROC']:.4f}. The training-validation gap therefore changes from "
        f"{gaps.iloc[0]:.4f} to {gaps.iloc[-1]:.4f}. High training performance together with a lower "
        f"validation score at small sample sizes indicates overfitting rather than underfitting: the model "
        f"can fit the available rows, but its estimates generalize less reliably. The largest validation gain "
        f"occurs between {largest_from:,} and {largest_to:,} examples. {ending} These conclusions apply to "
        f"the fixed in-distribution split and may not fully predict performance on shifted Kaggle test data."
    )


def write_report_snippet(results: pd.DataFrame, model_name: str, plot_path: Path, path: Path) -> None:
    rows = "\n".join(
        f"{int(r['training rows']):,} & {r['train AUROC']:.4f} & {r['validation AUROC']:.4f} & "
        f"Nested balanced subset, seed {SPLIT_SEED} \\\\"
        for _, r in results.iterrows()
    )
    text = f"""% Auto-generated by python -m src.q2_learning_curve --model {model_name}
% Upload {plot_path.name} to Overleaf alongside the report source.

% Q2.1
\\begin{{tabularx}}{{\\linewidth}}{{@{{}}rrrr@{{}}}}\\toprule
Training rows & Training AUROC & Validation AUROC & Notes \\\\ \\midrule
{rows}
\\bottomrule\\end{{tabularx}}
\\smallnote{{Configuration held fixed at masked word-pattern 1--3-gram TF--IDF (up to 200{{,}}000
features) with logistic regression, $C=4.0$. Subsets are nested, class-balanced prefixes drawn from
the shared 8{{,}}000-row training partition; all points use the same 2{{,}}000-row validation set.}}

% Q2.2
\\begin{{figure}}[ht]
  \\centering
  \\includegraphics[width=0.78\\linewidth]{{{plot_path.name}}}
  \\caption{{Training and validation AUROC versus labeled training-set size. All points use the same
  fixed 2,000-row validation set and identical hyperparameters.}}
  \\label{{fig:q2-learning-curve}}
\\end{{figure}}

% Q2.3
{interpretation(results)}
"""
    path.write_text(text, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", default="masked_lr", choices=list(MODELS))
    parser.add_argument("--seed", type=int, default=SPLIT_SEED)
    args = parser.parse_args()

    train, val = load_split()
    if len(train) < max(TRAIN_SIZES):
        raise ValueError(f"need at least {max(TRAIN_SIZES)} training rows, found {len(train)}")
    ordered = nested_balanced_order(train, args.seed)

    out = RESULTS_DIR / "q2" / args.model
    out.mkdir(parents=True, exist_ok=True)
    rows = []
    for n_rows in TRAIN_SIZES:
        subset = ordered.iloc[:n_rows].copy()
        assert subset["label"].value_counts().to_dict() == {0: n_rows // 2, 1: n_rows // 2}
        model = MODELS[args.model]()
        start = time.perf_counter()
        model.fit(subset["text"], subset["label"])
        fit_seconds = time.perf_counter() - start
        train_p = model.predict_proba(subset["text"])[:, 1]
        val_p = model.predict_proba(val["text"])[:, 1]
        rows.append({
            "training rows": n_rows,
            "train AUROC": roc_auc_score(subset["label"], train_p),
            "validation AUROC": roc_auc_score(val["label"], val_p),
            "fit seconds": fit_seconds,
            "AI share": subset["label"].mean(),
            "subset seed": args.seed,
        })
        print(f"{n_rows:>5,} rows | train {rows[-1]['train AUROC']:.4f} | "
              f"val {rows[-1]['validation AUROC']:.4f} | {fit_seconds:.2f}s")

    results = pd.DataFrame(rows)
    csv_path = out / "q21_learning_curve.csv"
    plot_path = out / "q22_learning_curve.png"
    summary_path = out / "summary.md"
    report_path = Path(__file__).resolve().parents[1] / "report" / "q2_learning_curve.tex"
    results.to_csv(csv_path, index=False)
    make_plot(results, plot_path)
    summary_path.write_text(
        f"# Q2 results: {args.model} (fixed validation split, subset seed {args.seed})\n\n"
        + results.round(4).to_markdown(index=False)
        + "\n\n## Q2.3 draft\n\n"
        + interpretation(results)
        + "\n",
        encoding="utf-8",
    )
    write_report_snippet(results, args.model, plot_path, report_path)
    print(f"\nwrote {csv_path}, {plot_path}, {summary_path}, and {report_path}")


if __name__ == "__main__":
    main()
