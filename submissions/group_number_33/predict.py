"""Load the final trained model and write 3000 Kaggle probabilities; never fit a model."""
import argparse
import json
from pathlib import Path
import sys

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.ensemble import ExtraTreesClassifier
from threadpoolctl import threadpool_limits

TEAM = Path(__file__).resolve().parent
sys.path.insert(0, str(TEAM / 'code'))
from models.dave_extratrees.model import DaveExtraTreesClassifier
from models.dave_extratrees.train import RECIPE_FILE, _ids_valid, load_recipe, sha256, validate_submission


def run(args):
    output = args.out.resolve()
    if output.exists():
        raise ValueError(f'Output already exists: {output}; choose a new --out')
    recipe = load_recipe()
    # Only load a trusted local artifact generated by this team's train.py.
    bundle = joblib.load(args.model)
    if (not isinstance(bundle, dict) or bundle.get('mode') != 'final'
            or bundle.get('training_rows') != 10000
            or not isinstance(bundle.get('model'), DaveExtraTreesClassifier)):
        raise ValueError('Expected a final 10000-row model from train.py --mode final')
    model = bundle['model']
    if (model.n_training_rows_ != 10000 or model.classifier_.n_features_in_ != 145
            or model.classifier_.get_params() != ExtraTreesClassifier(**recipe['model_params']).get_params()
            or bundle.get('recipe_sha256') != sha256(RECIPE_FILE)
            or bundle.get('feature_source_sha256') != recipe['feature_source_sha256']
            or bundle.get('training_data_sha256') != recipe['data_sha256']['train.csv']):
        raise ValueError('Saved model does not match the selected recipe, features, or full training data')
    if bundle.get('versions', {}).get('sklearn') != sklearn.__version__:
        raise ValueError('Use the same scikit-learn version for training and prediction; install requirements.txt')
    data_dir = args.data_dir.resolve()
    for name in ('test.csv', 'sample_submission.csv'):
        if sha256(data_dir / name) != recipe['data_sha256'][name]:
            raise ValueError(f'{name} checksum differs from the original competition file')
    test = pd.read_csv(data_dir / 'test.csv')
    sample = pd.read_csv(data_dir / 'sample_submission.csv')
    if (list(test.columns) != ['id', 'text'] or len(test) != 3000
            or not _ids_valid(test) or test.text.isna().any()
            or not test.text.map(lambda value: isinstance(value, str)).all()
            or list(sample.columns) != ['id', 'label'] or not _ids_valid(sample)
            or len(sample) != 3000 or set(sample.id) != set(test.id)):
        raise ValueError('Expected the original 3000 test passages and matching sample-submission IDs')
    with threadpool_limits(limits=2):
        probabilities = model.predict_proba(test.text)[:, 1]
    by_id = pd.Series(probabilities, index=test.id)
    submission = pd.DataFrame({'id': sample.id, 'label': sample.id.map(by_id)})
    validate_submission(submission, test, sample)
    output.parent.mkdir(parents=True, exist_ok=True)
    submission.to_csv(output, index=False, mode='x')
    readback = pd.read_csv(output)
    validate_submission(readback, test, sample)
    np.testing.assert_allclose(readback.label, submission.label, rtol=0, atol=1e-12)
    print(json.dumps(dict(submission=str(output), rows=len(readback),
                          probability_min=float(readback.label.min()), probability_max=float(readback.label.max()),
                          sha256=sha256(output), verification='PASS: 3000 IDs, id/label schema, finite [0,1] probabilities'), indent=2))
    return output


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data-dir', type=Path, default=TEAM / 'data',
                        help='Directory containing test.csv and sample_submission.csv; train.csv is not needed')
    parser.add_argument('--model', type=Path, default=TEAM / 'artifacts/final/model.joblib',
                        help='Trusted local model written by train.py --mode final')
    parser.add_argument('--out', type=Path, default=TEAM / 'submission.csv', help='New output CSV; existing files are not overwritten')
    args = parser.parse_args(argv)
    try:
        return run(args)
    except (ValueError, OSError) as error:
        parser.exit(2, f'error: {error}\n')


if __name__ == '__main__':
    main()
