"""Produce the accepted reblend from the same model's baseline CSV, without GPU inference."""
import argparse
import hashlib
import io
import json
from pathlib import Path
import zipfile

import joblib
import numpy as np
import pandas as pd
from scipy.sparse import hstack

from src.baseline import style_matrix
from src.calibration import RankCalibration
from src.recipes import BASELINE_WEIGHTS, CURRENT_WEIGHTS


def load_bundle(path):
    if path.is_file():
        with zipfile.ZipFile(path) as archive:
            return joblib.load(io.BytesIO(archive.read('final_model/model.joblib')))
    return joblib.load(path/'model.joblib')


def calibrated_reference(bundle, texts):
    ensemble=bundle['ensemble']; model=ensemble.classical
    if not isinstance(ensemble.calibration,RankCalibration):
        raise ValueError('This shortcut requires the accepted independent quantile calibration.')
    x=hstack((model.word.transform(texts),model.char.transform(texts)),format='csr')
    raw=.35*model.lexical.decision_function(x)+.65*model.style.predict(style_matrix(texts),prediction_type='RawFormulaVal')
    columns=np.zeros((len(texts),4));columns[:,0]=raw
    return ensemble.calibration.transform(columns)[:,0]


def reblend_scores(baseline, reference):
    baseline=np.asarray(baseline,dtype=float);reference=np.asarray(reference,dtype=float)
    if baseline.shape!=reference.shape or baseline.ndim!=1 or not np.isfinite(baseline).all() or not np.isfinite(reference).all():
        raise ValueError('Expected matching finite score vectors.')
    # All three other components increase by the same factor in the accepted recipe.
    ratios=CURRENT_WEIGHTS[1:]/BASELINE_WEIGHTS[1:]
    if not np.allclose(ratios,ratios[0]):raise ValueError('This shortcut is invalid for the selected weights.')
    rest=(baseline-BASELINE_WEIGHTS[0]*reference)/(1-BASELINE_WEIGHTS[0])
    if np.any((rest < -1e-6)|(rest > 1+1e-6)):
        raise ValueError('Baseline scores are inconsistent with this model/recipe. Regenerate with --recipe baseline.')
    return np.clip(CURRENT_WEIGHTS[0]*reference+(1-CURRENT_WEIGHTS[0])*rest,0,1)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--model',type=Path,required=True,help='Extracted model directory or trusted four_method_bundle.zip')
    p.add_argument('--input',type=Path,required=True,help='The same id,text CSV used for the baseline predictions')
    p.add_argument('--baseline',type=Path,required=True,help='CSV generated by the SAME fitted model with --recipe baseline')
    p.add_argument('--output',type=Path,required=True);a=p.parse_args()
    if a.output.resolve()==a.baseline.resolve():raise ValueError('Preserve the baseline; choose a different output file.')
    text=pd.read_csv(a.input,keep_default_na=False);baseline=pd.read_csv(a.baseline,keep_default_na=False)
    if not {'id','text'}.issubset(text.columns) or list(baseline.columns)!=['id','label'] or not len(text):
        raise ValueError('Expected nonempty id,text input and id,label baseline.')
    if not text.id.equals(baseline.id) or text.id.duplicated().any():raise ValueError('IDs and row order must match exactly and be unique.')
    if not text.text.map(lambda value:isinstance(value,str) and bool(value.strip())).all():raise ValueError('Every passage must contain text.')
    scores=baseline.label.to_numpy(dtype=float)
    if not np.isfinite(scores).all() or np.any((scores<0)|(scores>1)):raise ValueError('Invalid baseline scores.')
    reference=calibrated_reference(load_bundle(a.model),text.text.to_numpy())
    result=reblend_scores(scores,reference)
    a.output.parent.mkdir(parents=True,exist_ok=True)
    pd.DataFrame({'id':text.id,'label':result}).to_csv(a.output,index=False)
    print(json.dumps({'rows':len(text),'output':str(a.output),'recipe':'current','weights':CURRENT_WEIGHTS.tolist(),
                      'baseline_sha256':hashlib.sha256(a.baseline.read_bytes()).hexdigest(),
                      'output_sha256':hashlib.sha256(a.output.read_bytes()).hexdigest()}))


if __name__=='__main__':main()
